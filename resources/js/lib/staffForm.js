/** Fill the form from an API staff object (user + profile). */
export function staffToForm(staff) {
    const base = emptyStaffForm();
    const p = staff.profile || {};
    const pick = (src) => Object.fromEntries(Object.keys(base).filter((k) => k in src).map((k) => [k, src[k] ?? base[k]]));
    const form = { ...base, ...pick(staff), ...pick(p), password: '', password_confirmation: '' };
    form.skills = p.skills || [];
    form.has_illness = p.has_illness === null || p.has_illness === undefined ? '' : p.has_illness ? '1' : '0';
    form.same_whatsapp = !p.whatsapp || p.whatsapp === staff.phone;
    form.same_address = !!p.permanent_address && p.permanent_address === staff.address;
    return form;
}

/** Build multipart data. Booleans become "1"/"0", empty values are skipped. */
export function staffFormData(form, files, extra = {}) {
    const fd = new FormData();
    const data = { ...form };
    if (data.same_whatsapp) data.whatsapp = data.phone;
    if (data.same_address) data.permanent_address = data.address;
    delete data.same_whatsapp;
    delete data.same_address;

    Object.entries({ ...data, ...extra }).forEach(([k, v]) => {
        if (k === 'skills') return v.forEach((s) => fd.append('skills[]', s));
        if (typeof v === 'boolean') return fd.append(k, v ? '1' : '0');
        if (v === '' || v === null || v === undefined) return;
        fd.append(k, v);
    });
    Object.entries(files).forEach(([k, f]) => f && fd.append(k, f, `${k}.jpg`));
    return fd;
}

/** Downscale a photo in the browser so uploads stay small (server limit is 2 MB). */
export function compressImage(file, maxSize = 1600, quality = 0.82) {
    return new Promise((resolve, reject) => {
        if (!file.type.startsWith('image/')) return reject(new Error('Please choose an image file.'));
        const img = new Image();
        const url = URL.createObjectURL(file);
        img.onload = () => {
            const scale = Math.min(1, maxSize / Math.max(img.width, img.height));
            const canvas = document.createElement('canvas');
            canvas.width = Math.round(img.width * scale);
            canvas.height = Math.round(img.height * scale);
            canvas.getContext('2d').drawImage(img, 0, 0, canvas.width, canvas.height);
            URL.revokeObjectURL(url);
            canvas.toBlob((blob) => (blob ? resolve(blob) : reject(new Error('Could not read image.'))), 'image/jpeg', quality);
        };
        img.onerror = () => {
            URL.revokeObjectURL(url);
            reject(new Error('Could not read image. Please try another photo.'));
        };
        img.src = url;
    });
}

/** Map Laravel 422 errors to { field: message } (skills.0 -> skills). */
export function mapErrors(err) {
    const errors = err?.response?.data?.errors || {};
    return Object.fromEntries(Object.entries(errors).map(([k, v]) => [k.split('.')[0], v[0]]));
}
